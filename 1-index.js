function t(L, key, vars) {
  let s = L[key] || LOCALES.en[key] || key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace("{" + k + "}", v);
  return s;
}

// ---------------- Scan engine ----------------

function normalizeUrl(raw) {
  let u = String(raw || "").trim();
  if (!u) return null;
  if (!/^https?:\/\//i.test(u)) u = "https://" + u;
  let url;
  try { url = new URL(u); } catch { return null; }
  if (!/^https?:$/.test(url.protocol)) return null;
  if (!/^(?!.*\.\.)[a-z0-9.-]+\.[a-z]{2,}(:\d{1,5})?$/i.test(url.host)) return null;
  return url;
}

const BLOCKED_HOST = /^(localhost|127\.|0\.|10\.|169\.254\.|192\.168\.|172\.(1[6-9]|2\d|3[01])\.|\[?::1|metadata\.google)/i;

function isBlockedHost(url) {
  return BLOCKED_HOST.test(url.hostname);
}

function stripToText(html) {
  return html
    .replace(/<script[\s\S]*?<\/script>/gi, " ")
    .replace(/<style[\s\S]*?<\/style>/gi, " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/&nbsp;/gi, " ")
    .replace(/&amp;/gi, "&")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 200000);
}

async function fetchPage(url) {
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), FETCH_TIMEOUT_MS);
  try {
    const res = await fetch(url.toString(), {
      redirect: "follow",
      signal: ctrl.signal,
      headers: {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36 AIActChecker/0.1",
        "Accept": "text/html,application/xhtml+xml,*/*;q=0.8",
        "Accept-Language": "en-US,en;q=0.9",
      },
    });
    if (!res.ok) return { error: "HTTP " + res.status };
    const ctype = res.headers.get("content-type") || "";
    if (!/text\/html|application\/xhtml/i.test(ctype)) return { error: "not an HTML page (" + ctype.split(";")[0] + ")" };
    const reader = res.body.getReader();
    const chunks = [];
    let total = 0;
    while (true) {
      const { done, value } = await reader.read();
      if (done) break;
      chunks.push(value);
      total += value.length;
      if (total >= MAX_HTML_BYTES) { try { await reader.cancel(); } catch {} break; }
    }
    const buf = new Uint8Array(total);
    let off = 0;
    for (const c of chunks) { buf.set(c, off); off += c.length; }
    return { html: new TextDecoder("utf-8", { fatal: false }).decode(buf), finalUrl: res.url };
  } catch (e) {
    return { error: (e && e.name === "AbortError") ? "timeout" : "fetch error" };
  } finally {
    clearTimeout(timer);
  }
}

function findMatches(text, patterns) {
  const hits = [];
  for (const p of patterns) {
    const m = text.match(p.re || p);
    if (m) hits.push({ name: p.name || null, sample: m[0].slice(0, 120) });
  }
  return hits;
}

function scan(url, html) {
  const text = stripToText(html);
  const chatVendors = findMatches(html, CHAT_SIGNATURES);
  const genericChat = findMatches(html, GENERIC_CHAT_DOM);
  const hasChat = chatVendors.length > 0 || genericChat.length > 0;

  // Disclosure check: look in visible text AND inline script/config blobs (widget greetings often live in JS)
  const disclosureHits = findMatches(text + " " + html.slice(0, 400000), AI_INTERACTION_DISCLOSURE);
  const contentLabelHits = findMatches(text, AI_CONTENT_LABEL);

  // Heuristic: a bare "AI assistant" mention in marketing copy is weaker than a greeting notice.
  const strongDisclosure = disclosureHits.some(h =>
    /chatting|talking|speaking|interacting|this is an automated|this conversation is with/i.test(h.sample));

  const checks = [];

  checks.push({
    id: "chat_feature",
    label: "AI/chat feature detected on page",
    status: hasChat ? "found" : "not_found",
    detail: hasChat
      ? "Detected: " + ([...new Set(chatVendors.map(h => h.name).filter(Boolean))].join(", ") || "generic chat widget")
      : "No known chat widget or AI-platform script found in the HTML.",
  });

  let dStatus, dDetail;
  if (!hasChat) {
    dStatus = "not_applicable";
    dDetail = "No chat/AI interaction detected, so Art. 50(1) notice may not be needed for this page.";
  } else if (strongDisclosure) {
    dStatus = "pass";
    dDetail = "Found an explicit notice that the visitor is interacting with an AI (" + disclosureHits[0].sample + ").";
  } else if (disclosureHits.length) {
    dStatus = "warn";
    dDetail = "Weak or ambiguous AI mention found (" + disclosureHits[0].sample + "). Make sure the chat clearly tells visitors they are talking to an AI, in or above the chat window.";
  } else {
    dStatus = "fail";
    dDetail = "Chat/AI feature detected but no notice telling visitors they interact with an AI. Art. 50(1) requires this (unless it is obvious from context).";
  }
  checks.push({ id: "chat_disclosure", label: "AI-interaction disclosure (Art. 50(1))", status: dStatus, detail: dDetail });

  let cStatus, cDetail;
  if (contentLabelHits.length) {
    cStatus = "pass";
    cDetail = "Found AI-content labeling text (" + contentLabelHits[0].sample + ").";
  } else {
    cStatus = "warn";
    cDetail = "No AI-content labels found on this page. If any text, image, audio or video here is AI-generated, Art. 50(2)/(4) requires visible labeling (and machine-readable marking for synthetic media).";
  }
  checks.push({ id: "content_label", label: "AI-generated content labeling (Art. 50(2)/(4))", status: cStatus, detail: cDetail });

  // Overall verdict
  let verdict, summary;
  if (checks.some(c => c.status === "fail")) {
    verdict = "LIKELY GAP";
    summary = "Transparency obligations under Article 50 look unmet on this page. Apply the fixes below.";
  } else if (checks.some(c => c.status === "warn")) {
    verdict = "NEEDS REVIEW";
    summary = "Some items need a human review or a stronger disclosure. See fixes below.";
  } else {
    verdict = "LOOKS OK";
    summary = "The checked Article 50 items look covered on this page.";
  }

  const fixes = [];
  if (dStatus === "fail" || dStatus === "warn") fixes.push({ ...FIXES.chat_disclosure, snippet: SNIPPETS.chat_notice });
  if (cStatus !== "pass") fixes.push({ ...FIXES.content_label, snippet: SNIPPETS.content_label });

  return { verdict, summary, checks, fixes };
}

