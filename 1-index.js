// ---------------- Worker entry ----------------

export default {
  async fetch(request, env) {
    const url = new URL(request.url);

    if (url.pathname === "/health") {
      return Response.json({ ok: true, version: VERSION });
    }

    if (url.pathname === "/" || url.pathname === "") {
      return new Response(`<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>AI Act Article 50 Checker</title><style>body{font-family:-apple-system,Segoe UI,Roboto,sans-serif;max-width:680px;margin:40px auto;padding:0 20px;color:#111}</style></head><body><h1>AI Act Article 50 Checker</h1><p>Free Telegram bot: send it a website URL and get a one-page verdict on EU AI Act Article 50 transparency (AI chat disclosure and AI-content labels), with ready-to-paste fixes.</p><p><a href="https://t.me/${esc(env.BOT_USERNAME || "")}">Open the Telegram bot</a></p><p><small>Transparency obligations apply since 2 August 2026. Automated first check, not legal advice.</small></p></body></html>`, { headers: { "content-type": "text/html; charset=utf-8" } });
    }

    if (url.pathname.startsWith("/r/")) {
      const id = url.pathname.slice(3).replace(/[^A-Za-z0-9]/g, "");
      const raw = await env.CHECKER.get("rep:" + id);
      if (!raw) return new Response("Report not found or expired.", { status: 404 });
      return new Response(reportHtml(JSON.parse(raw)), { headers: { "content-type": "text/html; charset=utf-8" } });
    }

    if (url.pathname === "/scan" && request.method === "GET") {
      const target = url.searchParams.get("url");
      if (!target) return Response.json({ ok: false, error: "missing url param" }, { status: 400 });
      const gate = await bumpCounter(env.CHECKER, "api:" + todayKey(), DAILY_GLOBAL_API_LIMIT);
      if (!gate.ok) return Response.json({ ok: false, error: "daily api limit reached" }, { status: 429 });
      const r = await runScanAndStore(env, target);
      if (r.error) return Response.json({ ok: false, ...r }, { status: 422 });
      return Response.json({ ok: true, report: r.report, reportUrl: (env.WORKER_ORIGIN || "") + "/r/" + r.report.id });
    }

    if (url.pathname === "/tg/webhook" && request.method === "POST") {
      const secret = request.headers.get("x-telegram-bot-api-secret-token");
      if (!env.WEBHOOK_SECRET || secret !== env.WEBHOOK_SECRET) {
        return new Response("forbidden", { status: 403 });
      }
      let update;
      try { update = await request.json(); } catch { return Response.json({ ok: true }); }
      const msg = update.message || update.edited_message;
      if (!msg || !msg.chat) return Response.json({ ok: true });

      const chatId = msg.chat.id;
      const L = locale(msg.from && msg.from.language_code);
      const text = (msg.text || "").trim();

      const reply = async (s) => { await sendMsg(env, chatId, s); };

      if (text.startsWith("/start")) { await reply(t(L, "welcome")); return Response.json({ ok: true }); }
      if (text.startsWith("/help")) { await reply(t(L, "help")); return Response.json({ ok: true }); }
      if (text.startsWith("/about")) { await reply(t(L, "about")); return Response.json({ ok: true }); }

      const candidate = extractUrl(text);
      if (!candidate) { await reply(t(L, "invalid_url")); return Response.json({ ok: true }); }

      const gate = await bumpCounter(env.CHECKER, "rl:" + chatId + ":" + todayKey(), DAILY_USER_LIMIT);
      if (!gate.ok) { await reply(t(L, "limit", { n: DAILY_USER_LIMIT })); return Response.json({ ok: true }); }

      await reply(t(L, "scanning", { url: candidate }));
      const r = await runScanAndStore(env, candidate);
      if (r.error === "invalid_url") { await reply(t(L, "invalid_url")); }
      else if (r.error === "blocked_url") { await reply(t(L, "blocked_url")); }
      else if (r.error === "fetch_failed") { await reply(t(L, "fetch_failed", { reason: r.reason })); }
      else { await reply(verdictMessage(env, L, r.report)); }
      return Response.json({ ok: true });
    }

    return new Response("not found", { status: 404 });
  },
};
